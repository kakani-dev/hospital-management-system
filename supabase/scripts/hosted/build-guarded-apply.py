#!/usr/bin/env python3
"""Build ONE guarded, single-transaction SQL script that applies repo migrations to hosted exactly like
`supabase db push` would (same SQL text, same schema_migrations row: version, name, statements).

Why not the Supabase MCP apply_migration tool: it records the migration under a NEW timestamp version
(that is how the history drifted on 2026-10-06 and needed the repair), so the repo and hosted would diverge.

Guards (any failure raises and the whole transaction rolls back, nothing is applied):
  1. history guard: schema_migrations must equal EXPECTED_BEFORE exactly (no partial / double apply).
  2. text guard: md5 of each recorded statement == md5 of the repo file computed here (exact text applied).
  3. post guard: history must equal EXPECTED_BEFORE + the applied versions.

Usage: build-guarded-apply.py --expect-before <v1,v2,...> <migration.sql> [<migration.sql> ...] > out.sql
       (prints a sha256/md5 manifest on stderr)
"""
import argparse, hashlib, os, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("--expect-before", required=True, help="comma-separated versions currently in schema_migrations")
ap.add_argument("files", nargs="+")
a = ap.parse_args()
before = [v.strip() for v in a.expect_before.split(",") if v.strip()]

out = ["-- GENERATED by supabase/scripts/hosted/build-guarded-apply.py; do not edit by hand.", "begin;",
       "set local lock_timeout = '10s';", "set local statement_timeout = '120s';",
       "do $guard$ begin",
       "  if (select coalesce(array_agg(version order by version), '{}') from supabase_migrations.schema_migrations)",
       f"     <> array[{', '.join(repr(v) for v in before)}]::text[] then",
       "    raise exception 'history guard: schema_migrations is not the expected pre-state; nothing applied';",
       "  end if;", "end $guard$;"]
applied = []
for path in a.files:
    base = os.path.basename(path)
    m = re.fullmatch(r"(\d{14})_(.+)\.sql", base)
    if not m:
        sys.exit(f"bad migration file name: {base}")
    version, name = m.groups()
    text = open(path, encoding="utf-8").read()
    tag = f"$hms_{version}$"
    if tag in text:
        sys.exit(f"dollar-quote tag {tag} occurs in {base}")
    md5 = hashlib.md5(text.encode()).hexdigest()
    sha = hashlib.sha256(text.encode()).hexdigest()
    print(f"{base} sha256={sha} md5={md5} bytes={len(text.encode())}", file=sys.stderr)
    out += [f"-- ===== {base} (sha256 {sha}) =====", text.rstrip("\n"), ";",
            "insert into supabase_migrations.schema_migrations (version, name, statements)",
            f"values ('{version}', '{name}', array[{tag}{text}{tag}]);",
            "do $guard$ begin",
            f"  if (select md5(statements[1]) from supabase_migrations.schema_migrations where version = '{version}') <> '{md5}' then",
            f"    raise exception 'text guard: recorded statement for {version} differs from the repo file';",
            "  end if;", "end $guard$;"]
    applied.append(version)
after = before + applied
out += ["do $guard$ begin",
        "  if (select array_agg(version order by version) from supabase_migrations.schema_migrations)",
        f"     <> array[{', '.join(repr(v) for v in after)}]::text[] then",
        "    raise exception 'post guard: unexpected history after apply';",
        "  end if;", "end $guard$;", "commit;"]
print("\n".join(out))

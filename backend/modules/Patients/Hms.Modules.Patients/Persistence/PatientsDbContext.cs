using Hms.Modules.Patients.Domain;
using Hms.Modules.Patients.Registry;
using Hms.SharedKernel.Persistence;
using Hms.SharedKernel.Tenancy;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;

namespace Hms.Modules.Patients.Persistence;

/// <summary>
/// Patient service schema ("patient"). Every query is filtered to the RESOLVED tenant via a
/// global query filter; with no resolved tenant, the filter matches nothing (fail closed).
/// SQL in supabase/migrations is the source of truth for the schema.
/// </summary>
public sealed class PatientsDbContext(DbContextOptions<PatientsDbContext> options, ITenantContext tenantContext) : DbContext(options)
{
    public const string Schema = "patient";

    public DbSet<Patient> Patients => Set<Patient>();

    /// <summary>patient.patient_phones (read-only here; written by patient.set_patient_phones).</summary>
    public DbSet<PatientPhoneNumber> PatientPhones => Set<PatientPhoneNumber>();

    /// <summary>
    /// Mapped to <c>patient.normalize_phone(text)</c> in PostgreSQL (so the expression index is used);
    /// evaluated in .NET by non-relational providers (unit tests).
    /// </summary>
    public static string? NormalizePhone(string? phone) => PatientPhone.Normalize(phone);

    // Evaluated per query (EF parameterizes DbContext instance members in query filters).
    private Guid CurrentTenantId => tenantContext.IsResolved ? tenantContext.TenantId : Guid.Empty;

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.HasDefaultSchema(Schema);

        modelBuilder.Entity<Patient>(e =>
        {
            e.ToTable("patients");
            // MRN is generated by the DB trigger (per-tenant counter) and immutable: never written by
            // EF (the client grants on mrn are revoked), read back from INSERT ... RETURNING.
            e.Property(x => x.Mrn).HasMaxLength(64).ValueGeneratedOnAdd();
            e.Property(x => x.Mrn).Metadata.SetBeforeSaveBehavior(PropertySaveBehavior.Ignore);
            e.Property(x => x.Mrn).Metadata.SetAfterSaveBehavior(PropertySaveBehavior.Ignore);
            e.HasIndex(x => new { x.TenantId, x.Mrn }).IsUnique();
            e.HasQueryFilter(p => p.TenantId == CurrentTenantId && !p.IsDeleted); // NOT is_deleted: matches the partial indexes

            // DEPRECATED mirror of the primary number (expand phase): written only by
            // patient.set_patient_phones (the client grants on phone are revoked), never by EF.
            e.Property(x => x.Phone).Metadata.SetBeforeSaveBehavior(PropertySaveBehavior.Ignore);
            e.Property(x => x.Phone).Metadata.SetAfterSaveBehavior(PropertySaveBehavior.Ignore);
            // Written only by patient.merge_patients (column grants revoked). Never sent by EF.
            foreach (var mergeColumn in new[] { nameof(Patient.MergedIntoPatientId), nameof(Patient.MergedAt), nameof(Patient.MergedBy) })
            {
                e.Property(mergeColumn).Metadata.SetBeforeSaveBehavior(PropertySaveBehavior.Ignore);
                e.Property(mergeColumn).Metadata.SetAfterSaveBehavior(PropertySaveBehavior.Ignore);
            }
        });

        modelBuilder.Entity<PatientPhoneNumber>(e =>
        {
            e.ToTable("patient_phones");
            e.Property(x => x.PhoneE164).HasColumnName("phone_e164").HasMaxLength(16);
            e.HasQueryFilter(p => p.TenantId == CurrentTenantId && !p.IsDeleted);
        });

        modelBuilder.HasDbFunction(typeof(PatientsDbContext).GetMethod(nameof(NormalizePhone), [typeof(string)])!)
            .HasSchema(Schema).HasName("normalize_phone");

        // Audit columns are DB-managed: never sent on INSERT/UPDATE; deleted_at never sent on INSERT.
        modelBuilder.UseDbManagedAuditColumns();

        // Sprint 2 (D1): soft delete / restore happen ONLY through patient.soft_delete_patient /
        // restore_patient (the update(deleted_at) grant is revoked), so EF never sends deleted_at at all.
        modelBuilder.Entity<Patient>().Property(x => x.DeletedAt).Metadata.SetAfterSaveBehavior(PropertySaveBehavior.Ignore);
    }
}

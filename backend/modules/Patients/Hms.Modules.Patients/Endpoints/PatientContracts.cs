using Hms.Modules.Patients.Domain;

namespace Hms.Modules.Patients.Endpoints;

/// <summary>List/search row. <c>DeletedAt</c> is only ever non-null for admins searching with includeDeleted.</summary>
public sealed record PatientSummaryDto(
    Guid Id, string Mrn, string FirstName, string LastName, DateOnly? DateOfBirth, string Sex, Guid RegisteredBranchId,
    string? Phone, DateTimeOffset? DeletedAt)
{
    public static PatientSummaryDto From(Patient p) =>
        new(p.Id, p.Mrn, p.FirstName, p.LastName, p.DateOfBirth, p.Sex, p.RegisteredBranchId, p.Phone, p.DeletedAt);
}

/// <summary>One stored number (E.164). The same number used for phone and WhatsApp is ONE entry with both flags.</summary>
public sealed record PatientPhoneDto(string Number, bool IsPrimary, bool IsWhatsapp)
{
    public static IReadOnlyList<PatientPhoneDto> From(IEnumerable<PatientPhoneNumber> rows) =>
        [.. rows.OrderByDescending(r => r.IsPrimary).ThenBy(r => r.PhoneE164, StringComparer.Ordinal)
            .Select(r => new PatientPhoneDto(r.PhoneE164, r.IsPrimary, r.IsWhatsapp))];

    /// <summary>Derived: the primary number is also the WhatsApp number.</summary>
    public static bool SameAsPhone(IReadOnlyList<PatientPhoneDto> phones) => phones.Any(p => p.IsPrimary && p.IsWhatsapp);
}

/// <summary>
/// WhatsApp input on create / update. <c>sameAsPhone: true</c> flags the phone number itself (needs a
/// phone); otherwise <c>number</c> is the WhatsApp number (null / empty = none).
/// </summary>
public sealed record WhatsappInput(bool? SameAsPhone, string? Number);

public sealed record PatientDetailDto(
    Guid Id, string Mrn, string FirstName, string LastName, DateOnly? DateOfBirth, string Sex, Guid RegisteredBranchId,
    string? Phone, DateTimeOffset? DeletedAt, string? Email, DateTimeOffset CreatedOn, DateTimeOffset UpdatedOn,
    IReadOnlyList<PatientPhoneDto> Phones, bool WhatsappSameAsPhone, string? AbhaNumber = null,
    bool DobEstimated = false, string? NoPhoneReason = null, string? KnownAllergies = null, RegistrationDetails? Details = null)
{
    public static PatientDetailDto From(Patient p, IReadOnlyList<PatientPhoneDto> phones) =>
        new(p.Id, p.Mrn, p.FirstName, p.LastName, p.DateOfBirth, p.Sex, p.RegisteredBranchId, PrimaryOr(p, phones), p.DeletedAt, p.Email,
            p.CreatedOn, p.UpdatedOn, phones, PatientPhoneDto.SameAsPhone(phones), p.AbhaNumber, p.DobEstimated, p.NoPhoneReason, p.KnownAllergies, RegistrationDetails.From(p));

    internal static string? PrimaryOr(Patient p, IReadOnlyList<PatientPhoneDto> phones) =>
        phones.FirstOrDefault(x => x.IsPrimary)?.Number ?? p.Phone;
}

/// <summary>201 body of POST /patients: the detail plus advisory duplicate warnings (D3; [] when none).</summary>
public sealed record PatientCreatedDto(
    Guid Id, string Mrn, string FirstName, string LastName, DateOnly? DateOfBirth, string Sex, Guid RegisteredBranchId,
    string? Phone, DateTimeOffset? DeletedAt, string? Email, DateTimeOffset CreatedOn, DateTimeOffset UpdatedOn,
    IReadOnlyList<DuplicateCandidateDto> DuplicateWarnings, IReadOnlyList<PatientPhoneDto> Phones, bool WhatsappSameAsPhone, string? AbhaNumber = null,
    bool DobEstimated = false, string? NoPhoneReason = null, string? KnownAllergies = null, RegistrationDetails? Details = null)
{
    public static PatientCreatedDto From(Patient p, IReadOnlyList<DuplicateCandidateDto> warnings, IReadOnlyList<PatientPhoneDto> phones) =>
        new(p.Id, p.Mrn, p.FirstName, p.LastName, p.DateOfBirth, p.Sex, p.RegisteredBranchId, PatientDetailDto.PrimaryOr(p, phones), p.DeletedAt,
            p.Email, p.CreatedOn, p.UpdatedOn, warnings, phones, PatientPhoneDto.SameAsPhone(phones), p.AbhaNumber, p.DobEstimated, p.NoPhoneReason, p.KnownAllergies, RegistrationDetails.From(p));
}

public sealed record DuplicateCandidateDto(
    Guid Id, string Mrn, string FirstName, string LastName, DateOnly? DateOfBirth, string? Phone, Guid RegisteredBranchId,
    IReadOnlyList<string> MatchReasons);

public sealed record DuplicateCheckResponse(IReadOnlyList<DuplicateCandidateDto> Candidates);

/// <summary>
/// NOTE: there is intentionally no TenantId property. The tenant always comes from the
/// server-resolved tenant context; any "tenantId" a client sends in JSON is ignored.
/// Likewise there is no Mrn: the MRN is generated by the database and any "mrn" in the JSON is ignored.
/// </summary>
public sealed record CreatePatientRequest(
    string? FirstName,
    string? LastName,
    DateOnly? DateOfBirth,
    string? Sex,
    Guid RegisteredBranchId,
    string? Phone,
    string? Email,
    WhatsappInput? Whatsapp = null,
    string? AbhaNumber = null,
    /// <summary>Required when the name matches a live patient (date of birth may be blank). Ignored unless there is a name match. Does not override email, phone or ABHA.</summary>
    string? DuplicateOverrideReason = null,
    /// <summary>#190: age in years when the date of birth is not known; the DOB is estimated and flagged. Ignored when DateOfBirth is sent.</summary>
    int? AgeYears = null,
    /// <summary>#190: why the patient has no mobile number. Required when Phone is blank on registration.</summary>
    string? NoPhoneReason = null,
    /// <summary>#275: known allergies (free text, max 500). Blank = not recorded.</summary>
    string? KnownAllergies = null,
    /// <summary>#58: address, emergency contact, guardian, blood group, referral. Required parts follow the tenant's registration settings.</summary>
    RegistrationDetails? Details = null);

/// <summary>
/// Body of POST /api/v1/patients/search. The terms travel in the body (not the URL) so names, MRNs,
/// phones and DOBs never land in proxy/edge access logs (review Minor 5). Filters are AND-ed.
/// </summary>
public sealed record PatientSearchRequest(
    string? Search, int? Page, int? PageSize, string? Phone = null, DateOnly? DateOfBirth = null, bool? IncludeDeleted = null,
    /// <summary>Exact ABHA number (14 digits, dashes optional). OP Counter unified search.</summary>
    string? Abha = null);

/// <summary>GET /patients/stats: counts for the dashboard (soft-deleted patients excluded).</summary>
public sealed record PatientStatsDto(long Total, long RegisteredToday);

public sealed record DuplicateCheckRequest(
    string? FirstName, string? LastName, DateOnly? DateOfBirth, string? Phone, Guid? ExcludePatientId,
    string? Email = null, string? AbhaNumber = null);

public sealed record DeletePatientRequest(string? Reason);

/// <summary>Body of POST /patients/{survivorId}/merge. Tenant admin only. The duplicate chart is soft-deleted.</summary>
public sealed record MergePatientRequest(Guid? DuplicatePatientId, string? Reason);

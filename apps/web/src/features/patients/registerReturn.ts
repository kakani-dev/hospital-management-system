import type { PatientSummary } from '../../lib/api/types'

/**
 * "No match → Register new patient → come back with the patient selected". Everything travels in
 * router (history) state, never in the URL: the typed name is PHI.
 */
export interface RegisterReturn {
  /** Path (with ?query) to return to after registering. */
  to: string
  /** Extra state handed back on return (e.g. the booking panel's practitioner/date/slot). */
  state?: Record<string, unknown>
}

export interface RegisterPatientState {
  returnTo?: string
  returnState?: Record<string, unknown>
  prefill?: Partial<Record<'firstName' | 'lastName' | 'phone', string>>
}

/** State present on the page we return to. */
export interface ReturnedPatientState {
  pickedPatient?: PatientSummary
  [key: string]: unknown
}

/**
 * Best-effort split of a search term into register-form fields ("First Last" / "Last, First").
 * Phone-like terms pre-fill the phone (with the hospital's calling code unless a + code is typed); other terms with digits (MRNs) pre-fill nothing: the MRN is generated by the server on registration.
 */
export function prefillFromTerm(term: string, countryCode?: string | null): RegisterPatientState['prefill'] {
  const t = term.trim()
  if (!t) return {}
  // Phone-shaped (digits, spaces, dashes, brackets, optional +; 7+ digits): pre-fill the phone with the
  // hospital's calling code (tenant default_country_code). Unknown code: as typed (the server applies it).
  if (/^\+?[0-9()\s.-]+$/.test(t) && t.replace(/\D/g, '').length >= 7) return { phone: t.startsWith('+') || !countryCode ? t : `${countryCode} ${t}` }
  if (/\d/.test(t)) return {}
  if (t.includes(',')) {
    const [last, ...first] = t.split(',')
    return { lastName: last!.trim(), firstName: first.join(',').trim() }
  }
  const [first, ...rest] = t.split(/\s+/)
  return { firstName: first!, lastName: rest.join(' ') }
}

#!/usr/bin/env python3
"""Create SYNTHETIC demo staff logins for the MediCore demo tenant.

Writes generated passwords ONLY to /workspace/secrets/medicore-demo-logins.txt (chmod 600, never
committed) and prints SQL (bcrypt hashes only) to stdout. Run that SQL against the database
BEFORE seed-demo-data.sql. Idempotent: existing passwords in the secrets file are kept
(re-hashed with the same value) and the SQL uses ON CONFLICT DO NOTHING, so existing users,
including demo.admin@demo.medicore.test, are never changed.
"""
import os, secrets, string, uuid, bcrypt, sys

SECRETS = os.environ.get("DEMO_LOGINS_FILE", "/workspace/secrets/medicore-demo-logins.txt")
NS = uuid.UUID("6f1d3c52-6a0e-4e55-9b51-0d3e5eed5eed")
DOMAIN = "demo-seed.example.com"
USERS = [  # local part, display name
    ("nurse.hyd", "Nurse Kavitha (Hyderabad, synthetic)"),
    ("reception.blr", "Reception Blr (synthetic)"), ("nurse.blr", "Nurse Blr (synthetic)"),
    ("billing.blr", "Billing Blr (synthetic)"), ("dr.arjun", "Dr. Arjun Hegde (synthetic)"),
    ("dr.meenakshi", "Dr. Meenakshi Iyer (synthetic)"),
    ("reception.chn", "Reception Chn (synthetic)"), ("nurse.chn", "Nurse Chn (synthetic)"),
    ("billing.chn", "Billing Chn (synthetic)"), ("dr.karthik", "Dr. Karthik Subramanian (synthetic)"),
]

existing = {}
if os.path.exists(SECRETS):
    for line in open(SECRETS):
        parts = line.strip().split("\t")
        if len(parts) == 2 and "@" in parts[0]:
            existing[parts[0]] = parts[1]

rows = []
for local, name in USERS:
    email = f"{local}@{DOMAIN}"
    pw = existing.get(email) or "Demo-" + "".join(secrets.choice(string.ascii_letters + string.digits) for _ in range(14))
    existing[email] = pw
    h = bcrypt.hashpw(pw.encode(), bcrypt.gensalt(10)).decode()
    rows.append((str(uuid.uuid5(NS, email)), email, name, h))

os.makedirs(os.path.dirname(SECRETS), exist_ok=True)
fd = os.open(SECRETS, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write("# MediCore demo staff logins (SYNTHETIC). Never commit or share. email<TAB>password\n")
    f.write("# Tenant admin demo.admin@demo.medicore.test keeps its existing password (not stored here).\n")
    for e, p in existing.items():
        f.write(f"{e}\t{p}\n")
os.chmod(SECRETS, 0o600)

out = sys.stdout
out.write("-- generated by scripts/demo/create-demo-logins.py (hashes only)\n")
for uid, email, name, h in rows:
    out.write(f"""insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
  raw_app_meta_data, raw_user_meta_data, confirmation_token, recovery_token, email_change_token_new, email_change, created_at, updated_at)
values ('00000000-0000-0000-0000-000000000000', '{uid}', 'authenticated', 'authenticated', '{email}', '{h}', now(),
  '{{"provider":"email","providers":["email"]}}', '{{"synthetic":true,"demo_seed":true}}', '', '', '', '', now(), now())
on conflict (id) do nothing;
insert into auth.identities (provider_id, user_id, identity_data, provider, created_at, updated_at)
values ('{uid}', '{uid}', '{{"sub":"{uid}","email":"{email}","email_verified":true}}', 'email', now(), now())
on conflict do nothing;
insert into identity.user_profiles (id, email, display_name) values ('{uid}', '{email}', '{name}') on conflict (id) do nothing;
""")
